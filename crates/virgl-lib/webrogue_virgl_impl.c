void webrogue_map_fd(int32_t fd, void* addr, size_t size) {
  void* ret = mmap(addr, size, PROT_READ | PROT_WRITE, MAP_SHARED | MAP_FIXED, fd, 0);
  if(addr != ret) {
    abort();
  }
}

